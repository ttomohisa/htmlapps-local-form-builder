'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const os = require('node:os');
const { pathToFileURL } = require('node:url');
const { test } = require('node:test');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const appPath = path.resolve(process.env.FORM_BUILDER_HTML || path.join(__dirname, '../dist/index.html'));

test('imported field IDs stay inert and preserve preview and exported response keys', async () => {
  const marker = 'window.__formIdInjected=1';
  const id = `field"><img src=x onerror="${marker}">`;
  const types = ['text', 'textarea', 'email', 'tel', 'number', 'date', 'time', 'radio', 'select', 'checkbox', 'checkboxGroup', 'heading', 'paragraph', 'divider'];
  const fields = types.map((type, i) => ({ id: `${id}-${i}`, type, label: `Synthetic ${type}`, helper: 'Synthetic helper', required: i === 0, defaultValue: type === 'checkboxGroup' ? [] : type === 'checkbox' ? false : '', options: ['A', 'B'] }));
  const pkg = { format: 'browser-kitty-local-form', formatVersion: 1, language: 'en', form: { schemaVersion: 1, formVersion: 1, formId: 'synthetic-security-form', title: 'Synthetic audit form', description: '', inputMode: 'normal', fields } };
  const html = '<!doctype html><script id="local-form-schema" type="application/json">' + JSON.stringify(pkg).replace(/</g, '\\u003c') + '</script>';
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end(fs.readFileSync(appPath)); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const downloadDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'local-form-id-test-'));
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true });
  const context = await browser.newContext({ acceptDownloads: true });
  const page = await context.newPage();
  const errors = [], outbound = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/*', route => { const url = route.request().url(); if (/^https?:/.test(url) && new URL(url).hostname !== '127.0.0.1') { outbound.push(url); return route.abort(); } return route.continue(); });
  await page.addInitScript(() => { window.__formIdInjected = 0; });
  try {
    await page.goto(process.env.FORM_BUILDER_DIRECT_FILE === '1' ? pathToFileURL(appPath).href : `http://127.0.0.1:${server.address().port}/index.html`);
    await page.locator('#importHtmlInput').setInputFiles({ name: 'synthetic-form.html', mimeType: 'text/html', buffer: Buffer.from(html) });
    await page.waitForTimeout(250);
    if (await page.locator('#appConfirmDialog[open]').count()) await page.locator('#appConfirmOk').click();
    await page.waitForTimeout(250);
    assert.equal(await page.evaluate(() => window.__formIdInjected), 0, 'imported ID executed as markup');
    assert.deepEqual(await page.locator('#fieldList .field-card').evaluateAll(cards => cards.map(card => card.dataset.fieldId)), fields.map(field => field.id));
    assert.equal(await page.locator('#fieldList img[src=x]').count(), 0);
    await page.reload();
    await page.locator('#draftContinueButton').click();
    assert.equal(await page.evaluate(() => window.__formIdInjected), 0, 'resumed draft ID executed as markup');
    assert.deepEqual(await page.locator('#fieldList .field-card').evaluateAll(cards => cards.map(card => card.dataset.fieldId)), fields.map(field => field.id));
    await page.locator('#previewModeButton').click();
    assert.equal(await page.evaluate(() => window.__formIdInjected), 0, 'preview ID executed as markup');
    assert.equal(await page.locator('#fieldList [onerror]').count(), 0);
    assert.deepEqual(await page.locator('[data-preview-field-id]').evaluateAll(roots => roots.map(root => root.dataset.previewFieldId)), fields.slice(0, 11).map(field => field.id));
    await page.locator('#validatePreviewButton').click();
    assert.equal(await page.locator('.runtime-error').getAttribute('id'), `preview-error-${fields[0].id}`);
    assert.equal(await page.evaluate(() => window.__formIdInjected), 0, 'validation error ID executed as markup');
    await page.locator('[data-preview-control="text"]').fill('Synthetic response');
    const exportButton = page.locator('#exportFormButton');
    const downloadPromise = page.waitForEvent('download');
    await exportButton.click();
    const download = await downloadPromise;
    const generated = fs.readFileSync(await download.path(), 'utf8');
    assert.ok(generated.includes('synthetic-security-form'));
    const generatedPath = path.join(downloadDirectory, 'generated.html');
    await download.saveAs(generatedPath);
    const generatedPage = await context.newPage();
    generatedPage.on('pageerror', error => errors.push(error.message));
    await generatedPage.addInitScript(() => { window.__formIdInjected = 0; });
    await generatedPage.goto(pathToFileURL(generatedPath).href);
    assert.equal(await generatedPage.evaluate(() => window.__formIdInjected), 0, 'exported ID executed as markup');
    assert.equal(await generatedPage.locator('[data-control="text"]').getAttribute('data-field-id'), fields[0].id);
    assert.equal(await generatedPage.locator('[onerror]').count(), 0);
    assert.deepEqual(await generatedPage.locator('#local-form-schema').evaluate(node => JSON.parse(node.textContent).form.fields.map(field => field.id)), fields.map(field => field.id));
    await generatedPage.locator('[data-control="text"]').fill('Synthetic saved response');
    await generatedPage.locator('#checkButton').click();
    await generatedPage.locator('#completionHistoryButton').click();
    const backupPromise = generatedPage.waitForEvent('download');
    await generatedPage.locator('#backupJsonButton').click();
    const backup = JSON.parse(fs.readFileSync(await (await backupPromise).path(), 'utf8'));
    assert.equal(backup.responses.length, 1);
    assert.equal(backup.responses[0].values[fields[0].id], 'Synthetic saved response');
    assert.deepEqual(backup.form.fields.map(field => field.id), fields.map(field => field.id));
    assert.equal(await generatedPage.evaluate(() => window.__formIdInjected), 0);
    assert.deepEqual(outbound, []);
    assert.deepEqual(errors, []);
  } finally { await context.close(); await browser.close(); await new Promise(resolve => server.close(resolve)); fs.rmSync(downloadDirectory, { recursive: true, force: true }); }
});
